//
//  이사님 제보(2026-08-12): "시작할 때 5각형 크리스탈이 날아온다."
//  그 오각형은 아트가 아니라 `entities.js` 의 폴백 코드 도형이다 — `getSprite('C1')` 이 null 일 때만 그린다.
//
//  왜 null 이었나. dist 실측:
//      domContentLoaded          5,103ms
//      크리스탈 요청 시작        5,101ms   ← **여기가 문제**
//      크리스탈 완료             6,123ms
//
//  `preloadStyle()` 은 `main.js` 안에 있다. ES 모듈은 **import 그래프를 전부 받고 나서야** 본문이 실행된다.
//  main.js 266KB + three.module.js 670KB 를 다 받을 때까지 아트는 **한 바이트도 요청되지 않는다.**
//  main.js 안에서 호출 위치를 위로 올려도 소용없다 — 본문 시작 자체가 늦기 때문이다.
//
//  → 그래서 이 파일이 따로 있다. `sprites.js`(18KB, 의존성 1개)만 건드리므로 훨씬 빨리 실행되고,
//    아트 다운로드가 main.js 파싱과 **병렬로** 진행된다.
//
//  ⚠️ES 모듈은 URL 당 싱글턴이다 — main.js 가 나중에 같은 `sprites.js` 를 import 해도
//   **같은 인스턴스·같은 캐시**를 본다. 두 번 받지 않는다.
//  ⚠️게임 로직·스폰·밸런스와 무관하다. 받는 **시점**만 바꾼다.
//  ⚠️실패해도 게임을 막지 않는다 — 폴백 도형이 남아 있으므로 오브젝트가 사라지는 일은 없다.

